"""Operational briefing model.

The Overview and the module pages answer "what is happening right now". This
answers the three questions actually asked in a briefing:

    what matters right now · what changed recently · what should I be watching

`build_briefing_snapshot()` returns a plain data structure. It contains no Dash
components and no reportlab flowables, because BOTH the `/briefing` screen and
the briefing PDF render from it — one set of operational statements, so the
printed pack can never disagree with the screen it was generated from.

Two rules this module is built around:

* **Nothing here is generated by a language model.** Every sentence is
  assembled from stored values by fixed rules, so the same data always produces
  the same briefing and every number is traceable to a row in the database.
* **Derived information is labelled as derived.** Observations, official
  warnings and Passive Monitor's own extrapolations are separate types with
  separate rendering, and a projected flood ETA is never presented as a BoM
  forecast.

`as_of` exists so a briefing is not welded to `datetime.now()`. It sets the
reference clock for the change window and for freshness. Reconstructing the
*state* sections at a past moment needs the Phase C state journal, so until
then a snapshot reports `state_is_live=True` and the UI says so rather than
implying the KPIs are historical.
"""
import logging
from dataclasses import dataclass, field
from datetime import datetime, timedelta

import pandas as pd

from app import database, intel_feed
from app.config import load_config
from app.modules.fire import data as fire_data
from app.modules.flood import data as flood_data
from app.modules.flood import trend as flood_trend
from app.modules.power import data as power_data
from app.modules.roads import data as roads_data
from app.modules.storm import data as storm_data
from app.modules.weather import data as weather_data

log = logging.getLogger(__name__)

# Selectable "changes since" periods. 1 hour is the default: long enough to
# cover the gap between briefings, short enough that everything in it is still
# operationally live.
WINDOW_OPTIONS = [(30, "30 minutes"), (60, "1 hour"), (180, "3 hours"),
                  (360, "6 hours"), (720, "12 hours")]
DEFAULT_WINDOW_MINUTES = 60

# A source is flagged when it hasn't produced a cycle in this multiple of its
# own configured interval — so a 15-minute collector isn't called stale at 3
# minutes and an every-minute one isn't allowed to sit dead for an hour.
STALE_INTERVAL_MULTIPLE = 3
# ...with a floor, so a fast collector doesn't flap on one slow cycle.
STALE_FLOOR_MINUTES = 10

# Watch-point trigger: a gauge this close to its next threshold is worth
# naming even though it hasn't crossed it.
WATCH_DISTANCE_M = 0.5
# An AWS gust at or above this is called out as notable. Chosen to sit near the
# top of the network's normal range; it is OUR reporting threshold, not a
# warning criterion, and is described that way wherever it appears.
WATCH_GUST_KMH = 70

OBSERVED, PROJECTION = "observed", "projection"

VICEMERGENCY_LEVELS = ("Emergency Warning", "Watch and Act", "Advice")
# Emergency Warnings and Watch & Acts are always listed in full; Advices are
# capped at this many (see _warnings).
ADVICE_LIMIT = 5


# --------------------------------------------------------------------------- #
# Model
# --------------------------------------------------------------------------- #
@dataclass
class Kpi:
    """One headline figure. `value` is pre-formatted, "—" when unknown, so the
    screen and the PDF can never format the same number two different ways.

    `detail` carries the reading's location as a SEPARATE field rather than
    baked into the value: an extreme is meaningless without its station, but
    "78 km/h — Wilsons Promontory" set as one string wraps a KPI card onto
    three lines. Each surface joins them the way it can lay them out.
    """
    label: str
    value: str
    group: str
    accent: str = None
    alert: bool = False
    detail: str = None

    @property
    def full_value(self):
        """Value and location as one string, for text and table rendering."""
        return "%s — %s" % (self.value, self.detail) if self.detail else self.value


@dataclass
class Change:
    """A detected change from the Intelligence Feed, inside the window."""
    ts: datetime
    time: str
    headline: str
    lines: list
    severity: int
    severity_label: str
    hazard: str
    hazard_label: str
    entity_name: str
    url: str


@dataclass
class Warning:
    """An active warning. `source` separates the two authorities — VicEmergency
    community warnings and BoM warning products are not interchangeable.

    `level` is only set for VicEmergency, where Emergency Warning / Watch and
    Act / Advice is the meaningful split. BoM's `group_type` is deliberately
    NOT surfaced as a level: it reads as minor/moderate/major and would be
    mistaken for the flood gauge classification, which is a different scale
    entirely (the Weather page omits it for the same reason). BoM warnings are
    separated by warning TYPE instead, which is what they are actually chosen
    by; group_type still drives the ordering.
    """
    source: str
    kind: str
    title: str
    level: str = None
    location: str = ""
    action: str = None
    issued: datetime = None
    expires: datetime = None
    url: str = None


@dataclass
class Consequence:
    """A cross-layer situation: several facts about one place that are more
    significant together than apart. Assembled by rule from stored data."""
    title: str
    lines: list
    hazard: str = None
    url: str = None


@dataclass
class WatchPoint:
    """Something that has not triggered the most severe threshold but deserves
    attention. `kind` is OBSERVED or PROJECTION and must survive into the UI —
    an extrapolated ETA has to look different from a measurement."""
    title: str
    lines: list
    kind: str = OBSERVED
    url: str = None


@dataclass
class SourceStatus:
    name: str
    last_update: datetime = None
    age_minutes: float = None
    state: str = "ok"          # ok | stale | never
    detail: str = None

    @property
    def is_healthy(self):
        return self.state == "ok"


@dataclass
class BriefingSnapshot:
    generated_at: datetime
    as_of: datetime
    window_minutes: int
    window_label: str
    window_start: datetime
    situation: list = field(default_factory=list)
    changes: list = field(default_factory=list)
    warnings: list = field(default_factory=list)
    consequences: list = field(default_factory=list)
    watch_points: list = field(default_factory=list)
    weather: list = field(default_factory=list)
    sources: list = field(default_factory=list)
    # Advice-level VicEmergency warnings not listed (see ADVICE_LIMIT).
    omitted_advice: int = 0
    # False would mean the state sections were reconstructed for `as_of`;
    # until the Phase C journal exists they are always live.
    state_is_live: bool = True

    @property
    def generated_label(self):
        return self.generated_at.strftime("%d %b %Y %H:%M")

    @property
    def stale_sources(self):
        return [s for s in self.sources if not s.is_healthy]

    def warnings_from(self, source):
        return [w for w in self.warnings if w.source == source]

    @property
    def has_content(self):
        return bool(self.changes or self.warnings or self.consequences
                    or self.watch_points)


# --------------------------------------------------------------------------- #
# Formatting (shared by the screen and the PDF so they cannot drift)
# --------------------------------------------------------------------------- #
def _count(value):
    return "—" if value is None else "{:,}".format(int(value))


def _number(value, fmt="{:.1f}", unit=""):
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "—"
    try:
        text = fmt.format(float(value))
    except (TypeError, ValueError):
        return "—"
    if not unit:
        return text
    return text + unit if unit == "%" else text + " " + unit


def _plural(n, singular, plural=None):
    return "%d %s" % (n, singular if n == 1 else (plural or singular + "s"))


def _as_datetime(value):
    if value is None or isinstance(value, datetime):
        return value
    ts = pd.to_datetime(value, errors="coerce")
    return None if pd.isna(ts) else ts.to_pydatetime()


def _age_minutes(then, now):
    if then is None:
        return None
    return max(0.0, (now - then).total_seconds() / 60.0)


def describe_age(minutes):
    """"4 min ago" / "2 hr 10 min ago" / "never" — one wording everywhere."""
    if minutes is None:
        return "never"
    if minutes < 1:
        return "just now"
    if minutes < 90:
        return "%d min ago" % int(round(minutes))
    hours, mins = divmod(int(round(minutes)), 60)
    return "%d hr %d min ago" % (hours, mins) if mins else "%d hr ago" % hours


def window_label(minutes):
    for value, label in WINDOW_OPTIONS:
        if value == minutes:
            return label
    return "%d minutes" % minutes


